#!/usr/bin/env python3
"""What this engine costs, at the shape of a real corpus.

Run it to see the numbers; `--check` turns them into a gate.

Two pressures, and a change can be fine under one and terrible under the other:
**many documents** (an index over a folder, a setting applied across it) and
**one long document** (the payload the UI loads, the reading order of a dense
page). A two-page fixture shows neither, which is how three separate defects
survived a green test suite.

The default shape is taken from a real drive that was measured rather than
guessed: 61 documents, 1,049 pages, folders seven deep. Every page here is
generated by `engine/tests/fixtures/make_fixtures.py`, so this measures
structure and contains nobody's documents.
"""

from __future__ import annotations

import argparse
import json
import sys
import tempfile
import time
import tracemalloc
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "engine" / "tests" / "fixtures"))

#: The corpus to design for, from a real drive: 61 documents averaging 17
#: pages, folders seven deep, plus one long document because a book puts
#: different pressure on the engine than a shelf of pamphlets does.
DOCS, PAGES, LONG, DEPTH = 61, 17, 300, 7

#: Cost per doubling, which is what the budget is written in.
#:
#: Not milliseconds: CI machines vary by five times or more, so an absolute
#: limit either passes everything or flakes constantly. A growth ratio is the
#: same on any machine and catches the thing that actually hurts -- work that
#: grows faster than the corpus does. O(n log n) doubles at about 2.1x, O(n^2)
#: at about 4x, and the gap between them is wide enough to sit a limit in.
#:
#: Assigning boxes to bands once scanned every cut per box and grew at 3.5x.
#: A page of 800 lines cost 8.55 ms where it now costs 0.46 ms.
MAX_GROWTH = 2.6

#: Bytes do not vary by machine, so these are absolute. Per-document figures
#: are measured on the small corpus `--check` uses, where fixed overhead is
#: spread over fewer documents than it would be on a real one -- the real
#: corpus sits around 43 kB per document, this sees more.
#:
#: They are a ratchet, not a target: each is set a little above what the engine
#: costs today so that a regression fails, and none of them asserts that the
#: current number is good. `view` in particular is *not* good -- it returns the
#: whole document, so a 300-page book is megabytes where a page is kilobytes.
#: When it is paginated this limit should drop by two orders of magnitude.
MAX_INDEX_KB_PER_DOC = 90
MAX_VIEW_KB_PER_PAGE = 12


def build_pdf(path: Path, pages: int, subject: str) -> None:
    """A document of `pages` pages: a heading, body lines, and page furniture."""
    import make_fixtures as mf

    contents = []
    for i in range(pages):
        page = mf.Content()
        page.text(mf.LEFT, 740, mf.H1 if i == 0 else mf.H2, f"{subject} section {i + 1}", bold=True)
        for j in range(14):
            page.text(mf.LEFT, 700 - j * 14, mf.BODY, f"Line {j} of section {i + 1}, {subject}.")
        mf.furniture(page, i + 1)
        contents.append(page)

    pdf = mf.Pdf()
    plain = pdf.add(
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>"
    )
    bold = pdf.add(
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>"
    )
    resources = f"/Font << /F1 {plain} 0 R /F2 {bold} 0 R >>"
    pages_ref = len(pdf.objects) + 1 + 2 * len(contents)
    refs = []
    for content in contents:
        stream = pdf.stream("", content.render())
        refs.append(
            pdf.add(
                f"<< /Type /Page /Parent {pages_ref} 0 R /MediaBox [0 0 612 792] "
                f"/Resources << {resources} >> /Contents {stream} 0 R >>".encode()
            )
        )
    kids = " ".join(f"{r} 0 R" for r in refs)
    tree = pdf.add(f"<< /Type /Pages /Count {len(refs)} /Kids [{kids}] >>".encode())
    path.write_bytes(pdf.build(pdf.add(f"<< /Type /Catalog /Pages {tree} 0 R >>".encode())))


def corpus(docs: int, pages: int, long_pages: int = 0):
    """A workspace of `docs` documents, folders `DEPTH` deep."""
    from mdgest import ops
    from mdgest.store import Workspace

    tmp = Path(tempfile.mkdtemp())
    sources = tmp / "src"
    sources.mkdir()
    ws = Workspace(tmp / "ws")
    deep = "/".join(f"f{i}" for i in range(DEPTH - 1))
    folders = [deep, "f0/f1", "f0"]

    ids = []
    for i in range(docs):
        path = sources / f"doc-{i:03d}.pdf"
        build_pdf(path, pages, f"Widget{i:03d}")
        doc = ws.add_pdf(path.read_bytes(), path.name, folders[i % len(folders)])
        ops.analyze(ws, doc)
        ids.append(doc)

    long_doc = None
    if long_pages:
        path = sources / "long.pdf"
        build_pdf(path, long_pages, "Long")
        long_doc = ws.add_pdf(path.read_bytes(), "long.pdf", "books")
        ops.analyze(ws, long_doc)
    return ws, ids, long_doc


def seconds(call, runs: int = 5) -> float:
    """Best of `runs`, not the mean. A timing sample is noise on top of a
    floor, so the smallest reading is the closest to the real cost and the
    mean drifts with whatever else the machine was doing."""
    best = float("inf")
    for _ in range(runs):
        start = time.perf_counter()
        call()
        best = min(best, time.perf_counter() - start)
    return best


def index_over(ws):
    from mdgest import occurrences

    return occurrences.Index.over(ws, "")


# ---------------------------------------------------------------- the report


def profile(args) -> int:
    from mdgest import ops

    start = time.perf_counter()
    ws, ids, long_doc = corpus(args.docs, args.pages, args.long)
    print(
        f"{args.docs} documents of {args.pages} pages, folders {DEPTH} deep, "
        f"plus one of {args.long}  (ingested in {time.perf_counter() - start:.1f}s)\n"
    )

    print("many documents")
    print(f"  {'index over the workspace':<38}{seconds(lambda: index_over(ws)) * 1000:9.1f} ms")
    print(f"  {'verify the corpus':<38}{seconds(lambda: ops.verify_folder(ws, ''), 2) * 1000:9.1f} ms")

    tracemalloc.start()
    index = index_over(ws)
    peak = tracemalloc.get_traced_memory()[1]
    tracemalloc.stop()
    print(f"  {'index peak memory':<38}{peak / 1e6:9.1f} MB")
    print(f"  {'  per document':<38}{peak / 1024 / args.docs:9.1f} kB")
    print(f"  {'occurrences indexed':<38}{sum(len(e.occurrences) for e in index.by_key.values()):9d}")

    print("\none long document")
    view = ops.view(ws, long_doc)
    view_kb = len(json.dumps(view)) / 1024
    page_kb = len(json.dumps(ops.page_view(ws, long_doc, 1))) / 1024
    print(f"  {'view (the payload the UI loads)':<38}{seconds(lambda: ops.view(ws, long_doc)) * 1000:9.1f} ms")
    print(f"  {'  payload':<38}{view_kb / 1024:9.2f} MB")
    print(f"  {'  per page':<38}{view_kb / args.long:9.1f} kB")
    print(f"  {'one page on its own':<38}{page_kb:9.1f} kB")
    return 0


# ------------------------------------------------------------------ the gate


def check(args) -> int:
    """Growth ratios and byte budgets. Small corpora on purpose -- doubling is
    what detects the shape of the curve, and it has to run in CI."""
    from mdgest.pagemap import Box
    from mdgest.structure import xy_cut

    failures: list[str] = []

    def growth(label: str, call, small: int, large: int) -> None:
        ratio = seconds(lambda: call(large)) / max(seconds(lambda: call(small)), 1e-9)
        doublings = max((large // small).bit_length() - 1, 1)
        per_doubling = ratio ** (1 / doublings)
        ok = per_doubling <= MAX_GROWTH
        print(f"  {label:<34}{per_doubling:6.2f}x per doubling   {'ok' if ok else 'OVER'}")
        if not ok:
            failures.append(
                f"{label}: {per_doubling:.2f}x per doubling (limit {MAX_GROWTH}) "
                "— cost is growing faster than the corpus"
            )

    print("growth")
    growth(
        "reading order (xy_cut)",
        lambda n: xy_cut([(i, Box(72, 800 - i * 20 - 10, 500, 800 - i * 20)) for i in range(n)], 10.0),
        400,
        1600,
    )

    small_ws, small_ids, _ = corpus(args.docs, args.pages)
    large_ws, large_ids, _ = corpus(args.docs * 2, args.pages)
    ratio = seconds(lambda: index_over(large_ws)) / max(seconds(lambda: index_over(small_ws)), 1e-9)
    ok = ratio <= MAX_GROWTH
    print(f"  {'index over a corpus':<34}{ratio:6.2f}x per doubling   {'ok' if ok else 'OVER'}")
    if not ok:
        failures.append(f"index over a corpus: {ratio:.2f}x per doubling (limit {MAX_GROWTH})")

    print("\nsize")
    tracemalloc.start()
    index_over(large_ws)
    peak_kb = tracemalloc.get_traced_memory()[1] / 1024
    tracemalloc.stop()
    per_doc = peak_kb / len(large_ids)
    ok = per_doc <= MAX_INDEX_KB_PER_DOC
    print(f"  {'index memory per document':<34}{per_doc:6.1f} kB          {'ok' if ok else 'OVER'}")
    if not ok:
        failures.append(
            f"index memory: {per_doc:.0f} kB per document (limit {MAX_INDEX_KB_PER_DOC}) "
            "— the index keeps a few fields per block, not the analysis they came from"
        )

    from mdgest import ops

    long_ws, _, long_doc = corpus(0, 0, args.long)
    per_page = len(json.dumps(ops.view(long_ws, long_doc))) / 1024 / args.long
    ok = per_page <= MAX_VIEW_KB_PER_PAGE
    print(f"  {'view payload per page':<34}{per_page:6.1f} kB          {'ok' if ok else 'OVER'}")
    if not ok:
        failures.append(
            f"view payload: {per_page:.1f} kB per page (limit {MAX_VIEW_KB_PER_PAGE}) "
            "— a response the UI loads must not scale with document length"
        )

    if failures:
        print()
        for failure in failures:
            print(f"FAIL  {failure}", file=sys.stderr)
    return 1 if failures else 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 over budget")
    parser.add_argument("--docs", type=int, help=f"documents (default {DOCS}, or 8 with --check)")
    parser.add_argument("--pages", type=int, default=PAGES)
    parser.add_argument("--long", type=int, help=f"pages in the long document (default {LONG})")
    args = parser.parse_args()

    try:
        import mdgest.store  # noqa: F401
    except ImportError:
        print("the engine is not here yet; this measures it once it is.", file=sys.stderr)
        return 0

    # --check runs in CI, so it uses the smallest corpus that still shows a
    # curve. The default run is the real shape, for looking at.
    args.docs = args.docs or (8 if args.check else DOCS)
    args.long = args.long or (40 if args.check else LONG)
    return check(args) if args.check else profile(args)


if __name__ == "__main__":
    raise SystemExit(main())
